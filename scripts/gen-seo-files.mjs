// Regenerates public/sitemap.xml and the article list in public/llms.txt from
// the data files, before every build (see "build" in package.json).
//
// Why this exists: both files were hand-maintained. By September 2026 the
// sitemap still carried 2026-05-21 as the lastmod on 49 pages, and llms.txt
// listed the blog as bare slugs (no URLs an AI crawler could follow) and was
// missing the newest article. Generating them from data means a new page, a
// new trade or a new weekly article can no longer be left out.
//
// Plain Node, no dependencies: the data files are TypeScript, so they are read
// with regular expressions rather than imported. Keep slugs, titles and dates
// as single-quoted or double-quoted string literals on their own lines, which
// is how every data file here is already written.
//
// lastmod: blog posts use their own `date`. Every other page takes its value
// from data/seo-pages.json, which preserves the dates the sitemap already had.
// When a page's content is materially changed, update its date there. A route
// that has no entry yet gets today's date and is added to that file.

import fs from 'node:fs'

const SITE = 'https://www.tradieinsurance.co.nz'
const today = new Date().toISOString().slice(0, 10)
const read = (p) => fs.readFileSync(p, 'utf8')

function records(file) {
  // Split on each object's `slug:` so fields are read per record, not across them.
  const src = read(file)
  const parts = src.split(/\n\s*slug:\s*/).slice(1)
  return parts.map((p) => {
    const str = (key) => {
      const m = p.match(new RegExp(`\\n\\s*${key}:\\s*(['"])((?:\\\\.|(?!\\1).)*)\\1`))
      return m
        ? m[2]
            .replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)))
            .replace(/\\'/g, "'")
            .replace(/\\"/g, '"')
        : undefined
    }
    const slug = p.match(/^(['"])([^'"]+)\1/)?.[2]
    return { slug, title: str('title'), name: str('name'), date: str('date'), metaDesc: str('metaDesc'), excerpt: str('excerpt') }
  }).filter((r) => r.slug)
}

const landing = records('data/landing-pages.ts')
const trades = records('data/trade-types.ts')
const types = records('data/coverage-types.ts')
const posts = records('data/blog-posts.ts').sort((a, b) => (b.date || '').localeCompare(a.date || ''))

const STATIC = ['/', '/compare/', '/contact/', '/faqs/', '/coverage/', '/trades/', '/blog/', '/about/', '/disclaimer/', '/privacy/', '/terms/']

const meta = JSON.parse(read('data/seo-pages.json'))
let metaChanged = false
const entry = (path, fallback) => {
  if (!meta[path]) { meta[path] = { lastmod: today, ...fallback }; metaChanged = true }
  return meta[path]
}

const urls = []
for (const p of STATIC) urls.push({ path: p, ...entry(p, { changefreq: 'monthly', priority: '0.7' }) })
for (const t of types) urls.push({ path: `/types/${t.slug}/`, ...entry(`/types/${t.slug}/`, { changefreq: 'monthly', priority: '0.8' }) })
for (const t of trades) urls.push({ path: `/trades/${t.slug}/`, ...entry(`/trades/${t.slug}/`, { changefreq: 'monthly', priority: '0.8' }) })
for (const l of landing) urls.push({ path: `/tradie-insurance/${l.slug}/`, ...entry(`/tradie-insurance/${l.slug}/`, { changefreq: 'monthly', priority: '0.7' }) })
for (const b of posts) {
  const e = entry(`/blog/${b.slug}/`, { changefreq: 'monthly', priority: '0.6' })
  urls.push({ path: `/blog/${b.slug}/`, ...e, lastmod: b.date || e.lastmod })
}

// The blog index changes whenever a post is published.
const blogIdx = urls.find((u) => u.path === '/blog/')
if (blogIdx && posts[0]?.date) blogIdx.lastmod = posts[0].date

const xml =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<!-- Generated by scripts/gen-seo-files.mjs on every build. Do not edit by hand. -->\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls
    .map((u) => `  <url><loc>${SITE}${u.path}</loc><lastmod>${u.lastmod}</lastmod><changefreq>${u.changefreq}</changefreq><priority>${u.priority}</priority></url>`)
    .join('\n') +
  '\n</urlset>\n'
fs.writeFileSync('public/sitemap.xml', xml)

// llms.txt: replace only the "## Blog Articles" section; everything else in the
// file stays hand-written.
const llms = read('public/llms.txt')
const start = llms.indexOf('## Blog Articles')
if (start === -1) throw new Error('llms.txt: "## Blog Articles" heading not found')
const next = llms.indexOf('\n## ', start + 5)
const section =
  `## Blog Articles\n\nNewest first. Last updated: ${posts[0]?.date ?? today} (${posts.length} articles)\n\n` +
  posts.map((p) => `- ${SITE}/blog/${p.slug}/ (${p.date}): ${p.title}`).join('\n') +
  '\n\n'
fs.writeFileSync('public/llms.txt', llms.slice(0, start) + section + (next === -1 ? '' : llms.slice(next + 1)))

if (metaChanged) fs.writeFileSync('data/seo-pages.json', JSON.stringify(meta, null, 1) + '\n')

console.log(`gen-seo-files: sitemap ${urls.length} URLs, llms.txt ${posts.length} articles${metaChanged ? ', seo-pages.json updated' : ''}`)
